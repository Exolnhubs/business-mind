const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>('en')
  // Block children until saved locale is read so forceRTL is applied before first render.
  const [ready, setReady] = useState(false)

  useEffect(() => {
    AsyncStorage.getItem('rawaq_locale').then((v) => {
      const saved: Locale = v === 'ar' ? 'ar' : 'en'
      I18nManager.forceRTL(saved === 'ar')
      setLocale(saved)
      setReady(true)
    })
  }, [])

  async function toggleLocale() {
    const next: Locale = locale === 'en' ? 'ar' : 'en'
    await AsyncStorage.setItem('rawaq_locale', next)
    I18nManager.forceRTL(next === 'ar')
    setLocale(next)
  }

  const t = (key: string) => translations[locale][key] ?? key
  const isRTL = locale === 'ar'

  return (
    <LocaleContext.Provider value={{ locale, isRTL, t, toggleLocale }}>
      <View style={{ flex: 1, direction: isRTL ? 'rtl' : 'ltr' }}>
        {ready ? children : null}
      </View>
    </LocaleContext.Provider>
  )
}

export function useLocale() {
  const ctx = useContext(LocaleContext)
  if (!ctx) throw new Error('useLocale must be inside LocaleProvider')
  return ctx
}
